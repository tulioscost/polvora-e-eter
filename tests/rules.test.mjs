import assert from 'node:assert/strict';
import {calculatePool,evaluateFaces,damageAfterArmor,effectiveRD,maxPV,initialBPM,bpmName,canAdvance} from '../module/rules.mjs';
assert.equal(calculatePool({attribute:3,skill:2}),5);
assert.equal(calculatePool({attribute:9,skill:4,mod:5}),10);
assert.equal(calculatePool({attribute:1,skill:0,mod:-9}),0);
assert.equal(calculatePool({attribute:3,skill:2,bpm:105,underPressure:true}),4);
assert.equal(calculatePool({attribute:3,skill:2,bpm:155,underPressure:true}),3);
assert.equal(calculatePool({attribute:3,skill:2,pf:2,exposed:true}),4);
assert.equal(calculatePool({attribute:3,skill:2,circumstantial:4}),7);
assert.equal(calculatePool({attribute:3,skill:2,pv:5,maxPv:10,physical:true}),4);
assert.deepEqual(evaluateFaces([2,5,6,1,6],2),{faces:[2,5,6,1,6],successes:3,impetus:2,passed:true});
assert.equal(evaluateFaces([6,2,1,3],2).impetus,0);
assert.equal(damageAfterArmor(3,6,2),3);
assert.equal(damageAfterArmor(2,0,4),0);
assert.equal(effectiveRD(3,100),3);
assert.equal(effectiveRD(3,49),2);
assert.equal(effectiveRD(3,25),1);
assert.equal(effectiveRD(3,0),0);
assert.equal(effectiveRD(3,100,true),1);
assert.equal(maxPV(2),10);
assert.equal(initialBPM(2),60);
assert.equal(bpmName(180),'Crise');
assert.equal(canAdvance(6,9),false);
assert.equal(canAdvance(6,6),true);
